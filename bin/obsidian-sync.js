#!/usr/bin/env node

const fs = require('fs');
const os = require('os');
const path = require('path');
const crypto = require('crypto');

const marker = '<!-- Generated by PAUL Obsidian sync. Edit the .paul source instead. -->';
const configPath = path.join(process.env.APPDATA || path.join(os.homedir(), '.config'), 'paul-framework', 'obsidian.json');

function option(args, name) {
  const index = args.indexOf(name);
  if (index < 0) return undefined;
  if (!args[index + 1] || args[index + 1].startsWith('--')) throw new Error(`${name} needs a path`);
  return args[index + 1];
}

function readConfig(file) {
  if (!fs.existsSync(file)) return {};
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function safeName(name) {
  return name.replace(/[<>:"/\\|?*\x00-\x1f]/g, '-').replace(/[. ]+$/g, '').trim() || 'project';
}

function collectMarkdown(directory, root = directory) {
  if (!fs.existsSync(directory)) return [];
  const files = [];
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    if (entry.isSymbolicLink()) continue;
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...collectMarkdown(fullPath, root));
    else if (entry.isFile() && entry.name.endsWith('.md')) files.push(path.relative(root, fullPath));
  }
  return files;
}

function assertManaged(file) {
  if (fs.existsSync(file) && !fs.readFileSync(file, 'utf8').startsWith(marker)) {
    throw new Error(`Refusing to replace an existing note: ${file}`);
  }
}

function managedWrite(file, body, dryRun) {
  if (!dryRun) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, `${marker}\n\n${body}`, 'utf8');
  }
}

function sync(projectPath, vaultPath, dryRun = false) {
  const project = path.resolve(projectPath);
  const vault = path.resolve(vaultPath);
  const source = path.join(project, '.paul');
  if (!fs.existsSync(path.join(vault, '.obsidian'))) throw new Error(`Obsidian vault not found: ${vault}`);
  if (!fs.existsSync(source)) throw new Error(`PAUL project not found: ${source}`);

  const id = crypto.createHash('sha256').update(process.platform === 'win32' ? project.toLowerCase() : project).digest('hex').slice(0, 8);
  const folder = `${safeName(path.basename(project))}-${id}`;
  const destination = path.join(vault, '20 Projects', 'PAUL', folder);
  const sourceFiles = ['PROJECT.md', 'ROADMAP.md', 'STATE.md']
    .filter(file => fs.existsSync(path.join(source, file)))
    .concat(collectMarkdown(path.join(source, 'phases')).map(file => path.join('phases', file)));

  const writes = [];
  for (const relative of sourceFiles) {
    const content = fs.readFileSync(path.join(source, relative), 'utf8');
    writes.push([path.join(destination, relative), content]);
  }

  const links = sourceFiles.map(file => `- [[20 Projects/PAUL/${folder}/${file.replace(/\\/g, '/').replace(/\.md$/, '')}|${file.replace(/\\/g, '/')}]]`).join('\n');
  const overview = `# ${path.basename(project)} · PAUL\n\nSource project: \`${project}\`\n\nThese notes mirror PAUL's project state. Edit files in \`.paul/\`; the next sync refreshes this view.\n\n${links || 'No PAUL notes found yet.'}\n`;
  writes.push([path.join(destination, 'Overview.md'), overview]);
  for (const [file] of writes) assertManaged(file);
  for (const [file, body] of writes) managedWrite(file, body, dryRun);
  return { destination, count: sourceFiles.length + 1, dryRun };
}

function main(args) {
  const command = args[0];
  if (command === 'configure') {
    const vault = option(args, '--vault');
    if (!vault) throw new Error('Usage: obsidian-sync.js configure --vault <path>');
    const resolved = path.resolve(vault);
    if (!fs.existsSync(path.join(resolved, '.obsidian'))) throw new Error(`Obsidian vault not found: ${resolved}`);
    fs.mkdirSync(path.dirname(configPath), { recursive: true });
    fs.writeFileSync(configPath, JSON.stringify({ vault: resolved }, null, 2) + '\n');
    console.log(`Configured Obsidian vault: ${resolved}`);
    return;
  }
  if (command !== 'sync') throw new Error('Usage: obsidian-sync.js configure --vault <path> | sync [--project <path>] [--vault <path>] [--dry-run]');
  const project = option(args, '--project') || process.cwd();
  const local = readConfig(path.join(project, '.paul', 'obsidian.json'));
  const global = readConfig(configPath);
  const vault = option(args, '--vault') || local.vault || global.vault;
  if (!vault) {
    console.log('Obsidian sync skipped: no vault configured.');
    return;
  }
  const result = sync(project, vault, args.includes('--dry-run'));
  console.log(`${result.dryRun ? 'Would sync' : 'Synced'} ${result.count} notes to ${result.destination}`);
}

if (require.main === module) {
  try { main(process.argv.slice(2)); }
  catch (error) { console.error(`Obsidian sync: ${error.message}`); process.exitCode = 1; }
}

module.exports = { sync, main, configPath };
